#include <cstddef>
#include <cstdint>
#include <span>
#include <string>
#include <string_view>
#include <vector>

namespace viper {

enum class TrackObjectTaskRecordStatus : std::uint8_t {
    ignored_directive,
    end_of_track_directives,
    car_record_deferred,
    complete_record,
    visual_only,
    skipped_by_native_gate,
    malformed_line,
    unsupported_object_type,
    missing_model_resource,
    invalid_model_resource,
    incomplete_track_data,
};

struct TrackObjectTaskRecordRow {
    std::size_t source_row{};
    TrackObjectTaskRecordStatus status{
        TrackObjectTaskRecordStatus::ignored_directive};
    std::uint32_t record_tag{};
    std::vector<std::byte> record_bytes;
    std::string source_line;
};

struct TrackObjectTaskRecordMaterialization {
    // False when any object line needs another producer or native inputs are
    // unresolved. Complete per-row bytes remain available for integration.
    bool complete{};
    bool stopped_at_end{};
    std::vector<TrackObjectTaskRecordRow> rows;
};

// Materializes the non-car records generated by the 0x45C630 track.obt object
// loop. Resource bundles should include the active track bundle and shared
// model bundles. Car records are reported as deferred so a separate entrant
// producer can place them at their native source rows. No cursor prefix or
// configured-car records are inferred here.
[[nodiscard]] TrackObjectTaskRecordMaterialization
materialize_track_object_task_records(
    const TrackObjectTextTable& table,
    const TerrainSurfaceResourcePayload& terrain,
    std::span<const ResourceBundle* const> model_bundles,
    std::uint32_t track_state_selector_0x53b194,
    bool static_object_dispatch_enabled,
    bool compatibility_division_enabled);

} // namespace viper
